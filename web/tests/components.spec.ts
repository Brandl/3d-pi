import {test,expect} from '@playwright/test';

for(const mobile of [false,true]) test(`component reference library and safe chat drafts (${mobile?'mobile':'desktop'})`,async({page})=>{
  if(mobile)await page.setViewportSize({width:390,height:844});
  await page.route('**/auth/session',route=>route.fulfill({json:{csrf:'test-csrf'}}));
  await page.route('**/api/agent/state',route=>route.fulfill({json:{model:'test/model',busy:false,messages:[],activeTools:[],sequence:0}}));
  const writes:string[]=[];
  page.on('request',request=>{if(request.method()==='POST')writes.push(request.url());});
  await page.goto('/');
  if(mobile)await expect(page.locator('#mobile-navigation').getByRole('button',{name:'Chat',exact:true})).toBeEnabled();
  else await expect(page.locator('#chat-panel')).toBeVisible();
  await page.locator('#open-files').click();
  await page.getByRole('button',{name:'Components',exact:false}).click();
  const library=page.getByRole('dialog',{name:'Components'});
  await expect(library).toBeVisible();
  await expect(library.getByRole('heading',{name:'Slide-lock joint'})).toBeVisible();
  await library.getByRole('button',{name:'Parameters',exact:true}).click();
  await library.getByLabel('Clip length',{exact:true}).fill('85');
  await library.getByRole('button',{name:'Instructions',exact:true}).click();
  await expect(library.getByText(/Print a short fit coupon/)).toBeVisible();
  await library.getByRole('button',{name:'Source',exact:true}).click();
  await expect(library.locator('pre code')).toContainText('import');
  await library.getByRole('button',{name:'Prepare pi request'}).click();
  await expect(library.getByLabel('Component request draft')).toHaveValue(/"lock_length": 85/);
  await library.getByRole('button',{name:'Use draft in chat'}).click();
  await expect(library).not.toBeVisible();
  await expect(page.locator('#chat-input')).toHaveValue(/Do not publish without my confirmation/);
  expect(writes).toEqual([]);
  await page.locator('#open-files').click();
  await page.locator('#open-components').click();
  await library.getByLabel('Search components').fill('floor');
  await expect(library.locator('.component-card')).toHaveCount(1);
  await library.locator('.component-card').click();
  await library.getByRole('button',{name:'Instructions',exact:true}).click();
  await expect(library.getByText(/2.062 mm roof overhang/)).toBeVisible();
  await library.getByRole('button',{name:'Parameters',exact:true}).click();
  await library.getByLabel('Retaining shoulder',{exact:true}).fill('-1');
  await library.getByRole('button',{name:'Prepare pi request'}).click();
  await expect(library.getByRole('status')).toContainText('Enter finite');
  await library.getByLabel('Search components').fill('no such component');
  await expect(library.getByText('No matching components.')).toBeVisible();
  await page.keyboard.press('Escape');await expect(library).not.toBeVisible();
  expect(writes).toEqual([]);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
});
